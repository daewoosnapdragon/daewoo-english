"""Writes src/components/brand/flowerData.ts from the vectorizer's JSON."""
import json, sys
src = sys.argv[1] if len(sys.argv) > 1 else '/tmp/flowers.json'
d = json.load(open(src))
out = ['// Generated by scripts/brand/to_ts.py from the six class-flower drawings. Do not edit by hand.',
       '// Each flower: centre-line paths in drawing order ([d, length]), seed dots, the head box, where the head ends.',
       "export interface FlowerArt { paths: [string, number][]; dots: [number, number, number][]; head: [number, number, number, number]; bot: number; len: number }",
       'export const FLOWER_ART: Record<string, FlowerArt> = ' + json.dumps(d, separators=(',', ':')) + '\n']
open('src/components/brand/flowerData.ts', 'w').write('\n'.join(out))
print('wrote', sum(len(json.dumps(v)) for v in d.values()) // 1024, 'KB')
