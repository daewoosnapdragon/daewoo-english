"""Turns the objective bank files in this folder into supabase/seed-unit-objectives.sql.

    python3 -I scripts/catalogue/objectives/make_seed.py

Each *.json here is one book's bank (see BRIEF.md). Units are matched by series name, book level
and exact unit title. A unit that already has objectives is left alone, so the seed is safe to
re-run and never overwrites an edit made on the Bookshelf.
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', '..', 'supabase', 'seed-unit-objectives.sql')


def q(s):
    s = str(s)
    assert '$q$' not in s, s
    return f'$q${s}$q$'


def arr(xs):
    return f"ARRAY[{', '.join(q(x) for x in xs)}]::text[]" if xs else "'{}'::text[]"


def main():
    banks = []
    for path in sorted(glob.glob(os.path.join(HERE, '*.json'))):
        banks.append(json.load(open(path, encoding='utf-8')))
    series = sorted({b['series'] for b in banks})
    lines = [
        '-- Objective banks for every unit of ' + ', '.join(series) + ', written from each book\'s scope and sequence',
        '-- and the CCSS and WIDA 2020 standards. Generated by scripts/catalogue/objectives/make_seed.py from the',
        '-- bank files beside it; do not edit by hand. Run after migration-curriculum-objectives.sql and the book seeds.',
        '-- Safe to re-run: a unit that already has objectives is left alone, so edits made on the Bookshelf stay.',
        '-- The last query lists any unit of these series still without a bank (a title that does not match).',
        '',
    ]
    total_units = total_obj = 0
    for b in banks:
        rows = []
        for u in b['units']:
            for i, o in enumerate(u['objectives'], 1):
                rows.append(f"({q(u['title'])}, {i}, {q(o['text'])}, {arr(o.get('ccss', []))}, {arr(o.get('wida', []))})")
            total_units += 1
            total_obj += len(u['objectives'])
        lines.append(f"-- ── {b['series']}{' ' + b['level'] if b['level'] else ''}: {len(b['units'])} units, {len(rows)} objectives ──")
        lines.append('INSERT INTO curriculum_unit_objectives (unit_id, sort_order, text, ccss_codes, wida)')
        lines.append('SELECT u.id, v.ord, v.text, v.ccss, v.wida FROM (VALUES')
        lines.append(',\n'.join('  ' + r for r in rows))
        lines.append(') AS v(title, ord, text, ccss, wida)')
        lines.append('JOIN curriculum_units u ON u.title = v.title')
        lines.append(f"JOIN curriculum_books bk ON bk.id = u.book_id AND lower(bk.level_number) = lower({q(b['level'])})")
        lines.append(f"JOIN curriculum_series s ON s.id = bk.series_id AND lower(s.name) = lower({q(b['series'])})")
        lines.append('WHERE NOT EXISTS (SELECT 1 FROM curriculum_unit_objectives o WHERE o.unit_id = u.id);')
        lines.append('')
    names = ', '.join(f'lower({q(s)})' for s in series)
    lines.append('-- Units still without a bank:')
    lines.append('SELECT s.name AS series, bk.level_number AS level, u.title FROM curriculum_units u')
    lines.append('JOIN curriculum_books bk ON bk.id = u.book_id JOIN curriculum_series s ON s.id = bk.series_id')
    lines.append(f'WHERE lower(s.name) IN ({names}) AND NOT EXISTS (SELECT 1 FROM curriculum_unit_objectives o WHERE o.unit_id = u.id)')
    lines.append('ORDER BY s.name, bk.level_number, u.sort_order;')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{len(banks)} books, {total_units} units, {total_obj} objectives -> {os.path.relpath(OUT)}')


if __name__ == '__main__':
    main()
