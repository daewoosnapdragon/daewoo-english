"""Turns bank_content.py into supabase/seed-comment-phrases.sql.

    python3 -I scripts/comment-bank/make_seed.py

bank_content.py is the approved Fall 2026 comment bank (the spreadsheet Kyla reviewed was
built from the same file). Every row gets a stable seed_key, and the seed inserts with
ON CONFLICT DO NOTHING, so it is safe to re-run and never overwrites a phrase edited in the app.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bank_content as B  # noqa: E402

OUT = os.path.join(HERE, '..', '..', 'supabase', 'seed-comment-phrases.sql')
AREAS = [('reading', B.READING), ('phonics', B.PHONICS), ('writing', B.WRITING), ('speaking', B.SPEAKING), ('language', B.LANGUAGE)]
LADDER_AREA = {'Reading': 'reading', 'Phonics': 'phonics', 'Writing': 'writing', 'Speaking and listening': 'speaking', 'Language': 'language'}


def q(s):
    if s is None:
        return 'NULL'
    s = str(s)
    assert '$q$' not in s, s
    return f'$q${s}$q$'


def main():
    rows = []  # (seed_key, kind, area, tier, category, grades, doc, audience, band, rung, text, home1, home2, sort_order)
    for area, data in AREAS:
        for i, (tier, grades, doc, text) in enumerate(data, 1):
            rows.append((f'{area}-{i:03d}', 'sentence', area, tier, None, grades, doc, None, None, None, text, None, None, i))
    for i, (cat, tier, text) in enumerate(B.BEHAVIOR, 1):
        rows.append((f'behavior-{i:03d}', 'sentence', 'behavior', tier, cat, 'all', 'both', None, None, None, text, None, None, i))
    for i, (doc, text) in enumerate(B.OPENERS, 1):
        rows.append((f'opener-{i:03d}', 'opener', None, None, None, 'all', doc, None, None, None, text, None, None, i))
    n = 0
    for text in B.CLOSERS_STUDENT:
        n += 1
        rows.append((f'closer-{n:03d}', 'closer', None, None, None, 'all', 'both', 'student', None, None, text, None, None, n))
    for text in B.CLOSERS_PARENT:
        n += 1
        rows.append((f'closer-{n:03d}', 'closer', None, None, None, 'all', 'both', 'parents', None, None, text, None, None, n))
    for i, (area, band, rung, cls, h1, h2) in enumerate(B.LADDERS, 1):
        rows.append((f'ladder-{i:03d}', 'ladder', LADDER_AREA[area], None, None, 'all', 'both', None, band, rung, cls, h1, h2, i))

    out = [
        '-- The Fall 2026 comment bank behind the Phrases drawer (Reports → Report card).',
        '-- Generated by scripts/comment-bank/make_seed.py from bank_content.py; do not edit by hand.',
        '-- Run after migration-comment-phrases.sql. Safe to re-run: a phrase that is already',
        '-- there (by seed_key) is left alone, so edits made in the app stay.',
        f'-- {len(rows)} phrases.',
        '',
        'INSERT INTO comment_phrases (seed_key, kind, area, tier, category, grades, doc, audience, band, rung, text, home1, home2, sort_order) VALUES',
    ]
    vals = []
    for r in rows:
        vals.append('  (' + ', '.join(q(x) if not isinstance(x, int) else str(x) for x in r) + ')')
    out.append(',\n'.join(vals))
    out.append('ON CONFLICT (seed_key) DO NOTHING;')
    out.append('')
    out.append("SELECT kind, count(*) FROM comment_phrases GROUP BY kind ORDER BY kind;")
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{len(rows)} phrases → {os.path.relpath(OUT)}')


if __name__ == '__main__':
    main()
